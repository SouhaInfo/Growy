            <h3 class="article">Choosing A Bottle</h3>
            <p>Choosing a bottle can be as challenging as picking a formula. Manufacturers make all sorts of claims about their nipples working more like the human breast or their bottles preventing gas. I haven’t seen good scientific literature that supports these claims, so I can’t recommend one brand over another. </p>
            <br>

            <h3 class="article"> How Many Ounces?</h3>
            <p>Just like breastfed babies, bottle-fed newborns may start off slowly for 2 to 3 days, often taking only 1 to 2 ounces (30–60 mL) at a time. After the first 2 to 3 days of life she’ll probably be taking 2 to 3 ounces (60–90 mL) every 3 to 4 hours. Sometimes your baby may sleep 4 to 5 hours between bottles, but she’ll need a lot of food over the first month or so of life, so if she hasn’t awakened to eat after 5 hours it’s a good idea to go ahead and wake her up. You might even consider waking her up after 3 or 4 hours during the daytime, hoping she’ll sleep a little longer at night.</p>
            <br>

            <p>After the first month of life your infant is likely to take around 4 ounces from the bottle every 4 hours or so, at least on average. That intake rises gradually so that by age 6 months, she’ll take 6 to 8 ounces (180–240 mL) 4 or 5 times a day. Another way to think about normal intake is by weight; for every pound of body weight, your infant will consume around 2½ ounces (75 mL) per day. That said, every baby is different, and her doctor will weigh and measure her at each wellness examination to assess whether her growth is appropriate for her age.</p>
            <br>

            <h3 class="article">Hunger Cues</h3>
            <p>Whether you’re breastfeeding or bottle-feeding, your baby will give the same cues to let you know when she’s hungry and when she’s full. She will start rooting, scooting, sucking on her hand, and smacking her lips when she needs food. She will release the nipple, turn away, and often fall asleep when she’s full. As she grows she may fall asleep less often and instead look up and grin at you. You can be pretty confident at this point that the feeding is over, especially if she’s letting formula drip on your pants.</p>
            <br>

             <p>The 3 most common questions I answer about feeding, no matter the source, are:</p>

             <br>
             <ul>
             <li class="sentences">Is she getting enough?</li>
             <li class="sentences"> Is she getting too much?</li>
             <li class="sentences"> When will she stop waking up at night to feed?</li>
             </ul>
             <br>

             <p>The first question we’ve already answered. As for too much, it’s rare for a baby to need more than about 7 or 8 ounces per feeding or more than 36 ounces in a day. She may be sucking for comfort rather than hunger. As for the last question, most babies will be able to make it through the night without feeding sometime between age 2 and 4 months or when they weigh more than about 12 pounds. That really unfamiliar, energetic feeling you’ll have? It’s called a full-night’s sleep.</p>
             <br>

             <h3 class="article">What You Can Do</h3>
             <p>More important than the type of bottle or nipple you use is how you position your baby when she eats. You’ll want to support her in a semi-upright position, with her head cradled in the crook of your arm. Hold the bottle so that milk completely covers the nipple; that way your baby isn’t swallowing air. Try not to bottle-feed your baby while she’s on her back. Lying down increases the risk that she’ll choke, and it allows milk to run into her eustachian tubes, possibly causing middle ear infections. In the first few weeks of life you may have to gently touch the nipple to her cheek to stimulate the rooting reflex.</p>
             <br>

             <h4>When to Call the Doctor?<h4>
                <p>Overfeeding often results in spitting up and contributes to obesity. If your baby is taking more than 7 or 8 ounces per feeding or more than 36 ounces a day, address it with her doctor.</p>
